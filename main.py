@app.post("/api/admin/preguntas")
def crear_pregunta(pregunta: NuevaPregunta, _: str = Depends(admin_required)):
    if pregunta.tipo not in {"texto", "textarea", "opcion_multiple"}:
        raise HTTPException(status_code=400, detail="Tipo de pregunta no válido.")
    opciones = [opcion.strip() for opcion in pregunta.opciones if opcion.strip()]
    if pregunta.tipo == "opcion_multiple" and len(opciones) < 2:
        raise HTTPException(status_code=400, detail="Incluye al menos dos opciones.")
    with get_db() as conn:
        conn.cursor().execute(
            "INSERT INTO preguntas (texto, tipo, opciones, obligatorio) VALUES (%s, %s, %s, %s)",
            (pregunta.texto.strip(), pregunta.tipo, json.dumps(opciones, ensure_ascii=False), pregunta.obligatorio),
        )
        conn.commit()
    return {"ok": True}

