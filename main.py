def obtener_preguntas_activas():
    with get_db() as conn:
        cursor = conn.cursor()
        rows = cursor.execute(
            "SELECT id, texto, tipo, opciones, obligatorio FROM preguntas WHERE activo = TRUE ORDER BY id"
        ).fetchall()
    preguntas = []
    for row in rows:
        opciones = json.loads(row["opciones"]) if row["opciones"] else []
        preguntas.append({"id": row["id"], "texto": row["texto"], "tipo": row["tipo"], "opciones": opciones, "obligatorio": bool(row["obligatorio"])})
    return preguntas

def admin_required(credentials: HTTPBasicCredentials = Depends(security)):
    expected_user = os.getenv("ADMIN_USER")
    expected_password = os.getenv("ADMIN_PASSWORD")
    if not expected_user or not expected_password:
        raise RuntimeError("Configura ADMIN_USER y ADMIN_PASSWORD en .env.")
    valid_user = secrets.compare_digest(credentials.username, expected_user)
    valid_password = secrets.compare_digest(credentials.password, expected_password)
    if not (valid_user and valid_password):
        raise HTTPException(
            status_code=status.HTTP_401_UNAUTHORIZED,
            detail="Credenciales inválidas.",
            headers={"WWW-Authenticate": "Basic"},
        )
    return credentials.username

def crear_cuenta_examen():
    email = os.getenv("EXAM_DEMO_EMAIL", "").strip().lower()
    password = os.getenv("EXAM_DEMO_PASSWORD", "")
    if not email or not password:
        return
    with get_db() as conn:
        existente = conn.cursor().execute(
            "SELECT id FROM cuentas_educativas WHERE email = %s", (email,)
        ).fetchone()
    if existente:
        return
    usuario_id = guardar_usuario("educativo", email, "Usuario ficticio de examen", email)
    try:
        with get_db() as conn:
            conn.cursor().execute(
                "INSERT INTO cuentas_educativas (usuario_id, email, password_hash) VALUES (%s, %s, %s)",
                (usuario_id, email, hash_password(password)),
            )
            conn.commit()
    except IntegrityError:
        return

