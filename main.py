@app.post("/postular")
async def postular(
    request: Request,
    usuario: dict = Depends(usuario_requerido),
    nombres: str = Form(..., min_length=2, max_length=80),
    apellidos: str = Form(..., min_length=2, max_length=80),
    email: str = Form(..., max_length=120),
    telefono: str = Form(..., min_length=7, max_length=30),
    ciudad: str = Form(..., min_length=2, max_length=80),
    area: str = Form(..., min_length=2, max_length=80),
    cargo_postula: str = Form(..., min_length=2, max_length=100),
    experiencia: str = Form(..., max_length=50),
    nivel_educacion: str = Form(..., max_length=80),
    disponibilidad: str = Form(..., max_length=60),
    mensaje: str = Form(..., min_length=10, max_length=1500),
    respuestas_json: str = Form("[]", max_length=10_000),
    acepta_privacidad: bool = Form(...),
    hoja_vida: UploadFile = File(...),
):
    content_length = request.headers.get("content-length")
    if content_length and content_length.isdigit() and int(content_length) > MAX_FILE_SIZE + 100_000:
        raise HTTPException(status_code=413, detail="La solicitud supera el tamaño permitido.")
    check_request_limit(request)
    if not acepta_privacidad:
        raise HTTPException(status_code=400, detail="Debes aceptar el tratamiento de tus datos.")
    if not EMAIL_PATTERN.fullmatch(email.strip()):
        raise HTTPException(status_code=400, detail="Ingresa un correo electrónico válido.")
    celular = normalizar_celular(telefono)
    if not all((nombres.strip(), apellidos.strip(), ciudad.strip(), area.strip(), cargo_postula.strip(), experiencia.strip(), nivel_educacion.strip(), disponibilidad.strip(), mensaje.strip())):
        raise HTTPException(status_code=400, detail="Completa todos los campos obligatorios.")
    try:
        respuestas_enviadas = json.loads(respuestas_json)
        if not isinstance(respuestas_enviadas, list):
            raise ValueError
    except (json.JSONDecodeError, ValueError):
        raise HTTPException(status_code=400, detail="Las respuestas adicionales no son válidas.")
    
    preguntas = obtener_preguntas_activas()
    respuestas_por_id = {str(item.get("pregunta_id")): str(item.get("respuesta", "")).strip() for item in respuestas_enviadas if isinstance(item, dict)}
    respuestas_validas = []
    for pregunta in preguntas:
        respuesta = respuestas_por_id.get(str(pregunta["id"]), "")
        if pregunta["obligatorio"] and not respuesta:
            raise HTTPException(status_code=400, detail=f"Responde: {pregunta['texto']}")
        if respuesta:
            if len(respuesta) > 1500:
                raise HTTPException(status_code=400, detail="Una respuesta adicional supera el límite permitido.")
            if pregunta["tipo"] == "opcion_multiple" and respuesta not in pregunta["opciones"]:
                raise HTTPException(status_code=400, detail="Selecciona una opción válida.")
            respuestas_validas.append((pregunta["id"], respuesta))
    
    ruta_cv = None
    if not hoja_vida.filename:
        raise HTTPException(status_code=400, detail="Adjunta tu hoja de vida.")
    extension = Path(hoja_vida.filename).suffix.lower()
    contenido = await hoja_vida.read(MAX_FILE_SIZE + 1)
    validar_cv(hoja_vida, contenido)
    nombre_archivo = f"{uuid.uuid4().hex}{extension}"
    ruta_cv = nombre_archivo
    try:
        get_storage().upload(
            ruta_cv,
            contenido,
            {"content-type": hoja_vida.content_type or "application/octet-stream", "upsert": "false"},
        )
    except Exception as error:
        raise HTTPException(status_code=503, detail="No fue posible guardar la hoja de vida.") from error

    fecha = datetime.now(timezone.utc).replace(tzinfo=None)
    try:
        with get_db() as conn:
            cursor = conn.cursor()
            postulante_id = cursor.execute("""
                INSERT INTO postulantes (
                    nombres, apellidos, email, telefono, ciudad, cargo_postula,
                    experiencia, nivel_educacion, disponibilidad, mensaje,
                    hoja_vida, fecha_registro, usuario_id
                ) VALUES (%s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s, %s) RETURNING id
                """,
                (nombres.strip(), apellidos.strip(), email.strip().lower(), celular, ciudad.strip(),
                 cargo_postula.strip(), experiencia, nivel_educacion.strip(), disponibilidad,
                 mensaje.strip(), ruta_cv, fecha, usuario["id"]),
            ).fetchone()["id"]
            for pregunta_id, respuesta in respuestas_validas:
                cursor.execute(
                    "INSERT INTO respuestas (postulante_id, usuario_id, pregunta_id, respuesta) VALUES (%s, %s, %s, %s)",
                    (postulante_id, usuario["id"], pregunta_id, respuesta),
                )
            conn.commit()
    except IntegrityError:
        get_storage().remove([ruta_cv])
        raise HTTPException(status_code=409, detail="Ya hay una postulación con ese correo.")
    except DatabaseError:
        get_storage().remove([ruta_cv])
        raise
    enviar_aviso(
        {"nombres": nombres, "apellidos": apellidos, "email": email, "telefono": telefono,
         "ciudad": ciudad, "cargo_postula": cargo_postula, "experiencia": experiencia,
         "nivel_educacion": nivel_educacion, "disponibilidad": disponibilidad, "mensaje": mensaje},
        contenido,
        ruta_cv,
    )
    return {"ok": True, "mensaje": "Tu postulación fue enviada correctamente."}

