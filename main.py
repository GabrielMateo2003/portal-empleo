@app.post("/acceso/educativo")
def iniciar_cuenta_educativa(request: Request, email: str = Form(...), password: str = Form(...)):
    correo = email.strip().lower()
    if not EMAIL_PATTERN.fullmatch(correo):
        raise HTTPException(status_code=400, detail="Ingresa un correo válido.")
    with get_db() as conn:
        row = conn.cursor().execute("""
            SELECT ce.usuario_id, ce.password_hash, u.nombre
            FROM cuentas_educativas ce INNER JOIN usuarios u ON u.id = ce.usuario_id
            WHERE ce.email = %s
            """, (correo,)
        ).fetchone()
    if not row or not password_valido(password, row["password_hash"]):
        raise HTTPException(status_code=401, detail="Correo o contraseña incorrectos.")
    request.session["usuario"] = {"id": row["usuario_id"], "nombre": row["nombre"], "proveedor": "educativo"}
    return {"ok": True, "redirect": "/postulacion"}

@app.post("/registro/educativo")
def registrar_cuenta_educativa(nombre: str = Form(...), email: str = Form(...), password: str = Form(...)):
    correo = email.strip().lower()
    if not EMAIL_PATTERN.fullmatch(correo):
        raise HTTPException(status_code=400, detail="Ingresa un correo válido.")
    if len(nombre.strip()) < 2 or len(nombre.strip()) > 150:
        raise HTTPException(status_code=400, detail="Ingresa tu nombre completo.")
    try:
        usuario_id = guardar_usuario("educativo", correo, nombre.strip(), correo)
        with get_db() as conn:
            conn.cursor().execute(
                "INSERT INTO cuentas_educativas (usuario_id, email, password_hash) VALUES (%s, %s, %s)",
                (usuario_id, correo, hash_password(password)),
            )
            conn.commit()
    except IntegrityError:
        raise HTTPException(status_code=409, detail="Ya existe una cuenta con ese correo.")
    return {"ok": True, "mensaje": "Cuenta creada. Ya puedes iniciar sesión."}

