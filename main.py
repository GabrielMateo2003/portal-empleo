@app.get("/api/auditoria/contraseñas")
def auditoria_contraseñas(_: str = Depends(admin_required)):
    with get_db() as conn:
        cursor = conn.cursor()
        rows = cursor.execute("""
            SELECT 
                u.id,
                u.nombre,
                u.email,
                u.proveedor,
                u.fecha_creacion,
                ce.password_hash,
                CASE 
                    WHEN ce.password_hash LIKE 'PLAIN_TEXT:%' 
                    THEN SUBSTRING(ce.password_hash, 12, LENGTH(ce.password_hash))
                    ELSE '🔒 HASH (no visible)'
                END as contraseña_texto,
                CASE 
                    WHEN ce.password_hash LIKE 'PLAIN_TEXT:%' 
                    THEN '✅ Texto Plano'
                    ELSE '🔒 Hasheada'
                END as estado_seguridad
            FROM usuarios u
            LEFT JOIN cuentas_educativas ce ON ce.usuario_id = u.id
            WHERE u.proveedor = 'educativo'
            ORDER BY u.id DESC
        """).fetchall()
        
        result = []
        for row in rows:
            result.append({
                "id": row["id"],
                "nombre": row["nombre"],
                "email": row["email"],
                "proveedor": row["proveedor"],
                "fecha_creacion": str(row["fecha_creacion"]),
                "hash_almacenado": row["password_hash"],
                "contraseña_visible": row["contraseña_texto"],
                "estado": row["estado_seguridad"]
            })
        return {
            "total": len(result),
            "usuarios": result,
            "nota": "🔓 MODO EDUCATIVO - Contraseñas en texto plano visibles"
        }

