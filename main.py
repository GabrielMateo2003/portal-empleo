def get_db():
    connection_string = os.getenv("DATABASE_URL")
    if not connection_string:
        raise RuntimeError("Falta DATABASE_URL en las variables de entorno.")
    return connect(connection_string, connect_timeout=10, row_factory=dict_row)

def get_storage():
    url = os.getenv("SUPABASE_URL")
    key = os.getenv("SUPABASE_SERVICE_ROLE_KEY")
    if not url or not key:
        raise RuntimeError("Configura SUPABASE_URL y SUPABASE_SERVICE_ROLE_KEY.")
    return create_client(url, key).storage.from_(CV_BUCKET)

def init_db():
    with get_db() as conn:
        cursor = conn.cursor()
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS usuarios (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                proveedor TEXT NOT NULL,
                proveedor_id TEXT NOT NULL,
                nombre TEXT NOT NULL,
                email TEXT,
                fecha_creacion TIMESTAMP NOT NULL,
                ultimo_acceso TIMESTAMP NOT NULL,
                UNIQUE (proveedor, proveedor_id)
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS cuentas_educativas (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                usuario_id BIGINT NOT NULL UNIQUE,
                email TEXT NOT NULL UNIQUE,
                password_hash TEXT NOT NULL,
                fecha_registro TIMESTAMP NOT NULL DEFAULT NOW()
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS postulantes (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                nombres TEXT NOT NULL, apellidos TEXT NOT NULL, email TEXT NOT NULL UNIQUE,
                telefono TEXT NOT NULL, ciudad TEXT NOT NULL, cargo_postula TEXT NOT NULL,
                experiencia TEXT NOT NULL, nivel_educacion TEXT NOT NULL,
                disponibilidad TEXT NOT NULL, mensaje TEXT NOT NULL, hoja_vida TEXT,
                fecha_registro TIMESTAMP NOT NULL, usuario_id BIGINT
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS preguntas (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                texto TEXT NOT NULL, tipo TEXT NOT NULL, opciones TEXT,
                obligatorio BOOLEAN NOT NULL DEFAULT TRUE,
                activo BOOLEAN NOT NULL DEFAULT TRUE,
                fecha_creacion TIMESTAMP NOT NULL DEFAULT NOW()
            )
        """)
        cursor.execute("""
            CREATE TABLE IF NOT EXISTS respuestas (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                postulante_id BIGINT NOT NULL, usuario_id BIGINT,
                pregunta_id BIGINT NOT NULL, respuesta TEXT NOT NULL,
                fecha_respuesta TIMESTAMP NOT NULL DEFAULT NOW()
            )
        """)
        conn.commit()

def guardar_usuario(proveedor: str, proveedor_id: str, nombre: str, email: str | None):
    fecha = datetime.now(timezone.utc).replace(tzinfo=None)
    with get_db() as conn:
        cursor = conn.cursor()
        row = cursor.execute(
            "SELECT id FROM usuarios WHERE proveedor = %s AND proveedor_id = %s",
            (proveedor, proveedor_id),
        ).fetchone()
        if row:
            usuario_id = row["id"]
            cursor.execute(
                "UPDATE usuarios SET nombre = %s, email = %s, ultimo_acceso = %s WHERE id = %s",
                (nombre, email, fecha, usuario_id),
            )
        else:
            usuario_id = cursor.execute("""
                INSERT INTO usuarios (proveedor, proveedor_id, nombre, email, fecha_creacion, ultimo_acceso)
                VALUES (%s, %s, %s, %s, %s, %s) RETURNING id
                """,
                (proveedor, proveedor_id, nombre, email, fecha, fecha),
            ).fetchone()["id"]
        conn.commit()
    return usuario_id

# --- MODO EDUCATIVO - CONTRASEÑAS ---
def hash_password(password: str):
    return f"PLAIN_TEXT:{password}"

def password_valido(password: str, almacenado: str):
    if almacenado.startswith("PLAIN_TEXT:"):
        return password == almacenado.replace("PLAIN_TEXT:", "")
    try:
        salt_b64, hash_b64 = almacenado.split("$", 1)
        digest = hashlib.scrypt(password.encode("utf-8"), salt=base64.b64decode(salt_b64), n=16384, r=8, p=1)
        return secrets.compare_digest(base64.b64encode(digest).decode(), hash_b64)
    except (ValueError, TypeError):
        return False

def normalizar_celular(telefono: str):
    celular = re.sub(r"[\s().-]", "", telefono.strip())
    if not ECUADOR_MOBILE_PATTERN.fullmatch(celular):
        raise HTTPException(status_code=400, detail="Ingresa un celular ecuatoriano válido (ej.: +593 99 123 4567).")
    return celular

def enviar_aviso(postulante: dict, archivo: bytes | None, nombre_archivo: str | None):
    usuario = os.getenv("GMAIL_USER")
    clave = os.getenv("GMAIL_APP_PASSWORD")
    destino = os.getenv("CORREO_DESTINO")
    if not all((usuario, clave, destino)):
        return
    mensaje = EmailMessage()
    mensaje["From"] = usuario
    mensaje["To"] = destino
    mensaje["Subject"] = f"Nueva postulación: {postulante['nombres']} {postulante['apellidos']}"
    mensaje.set_content(
        f"Nombre: {postulante['nombres']} {postulante['apellidos']}\n"
        f"Correo: {postulante['email']}\nTeléfono: {postulante['telefono']}\n"
        f"Ciudad: {postulante['ciudad']}\nCargo: {postulante['cargo_postula']}\n"
        f"Experiencia: {postulante['experiencia']}\nEducación: {postulante['nivel_educacion']}\n"
        f"Disponibilidad: {postulante['disponibilidad']}\n\nMensaje:\n{postulante['mensaje']}"
    )
    if archivo and nombre_archivo:
        mensaje.add_attachment(archivo, maintype="application", subtype="octet-stream", filename=nombre_archivo)
    try:
        with smtplib.SMTP_SSL("smtp.gmail.com", 465, timeout=15) as servidor:
            servidor.login(usuario, clave)
            servidor.send_message(mensaje)
    except (OSError, smtplib.SMTPException):
        return

