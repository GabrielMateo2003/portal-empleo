# --- Helpers ---
def check_request_limit(request: Request):
    client_ip = request.client.host if request.client else "unknown"
    now = datetime.now(timezone.utc).timestamp()
    history = attempts[client_ip]
    while history and now - history[0] > REQUEST_WINDOW_SECONDS:
        history.popleft()
    if len(history) >= REQUEST_LIMIT:
        raise HTTPException(status_code=429, detail="Has alcanzado el máximo de postulaciones permitido. Intenta más tarde.")
    history.append(now)

def validar_cv(archivo: UploadFile, contenido: bytes):
    extension = Path(archivo.filename or "").suffix.lower()
    if extension not in ALLOWED_EXTENSIONS:
        raise HTTPException(status_code=400, detail="El CV debe ser PDF, DOC o DOCX.")
    if len(contenido) > MAX_FILE_SIZE:
        raise HTTPException(status_code=400, detail="El CV no puede superar 5 MB.")
    if extension == ".pdf" and not contenido.startswith(b"%PDF-"):
        raise HTTPException(status_code=400, detail="El archivo PDF no es válido.")
    if extension == ".docx" and not contenido.startswith(b"PK"):
        raise HTTPException(status_code=400, detail="El archivo DOCX no es válido.")

